// Land dots for the globe on the node dashboard: rows of points a fixed number of degrees apart, staggered, kept
// where Natural Earth says there is land (110m land, public domain). Writes src/lib/globe-dots.ts.
//   node scripts/globe-dots.mjs path/to/ne_110m_land.geojson
// The GeoJSON is the file of that name from github.com/nvkelso/natural-earth-vector (geojson/).
import fs from "node:fs";
import { booleanPointInPolygon } from "@turf/turf";

const file = process.argv[2];
if (!file) { console.error("usage: node scripts/globe-dots.mjs ne_110m_land.geojson"); process.exit(1); }
const fc = JSON.parse(fs.readFileSync(file, "utf8"));
const STEP = 1.6;
const out = [];
let row = 0;
for (let lat = -88; lat <= 88.01; lat += STEP, row++) {
  const n = Math.max(1, Math.round((360 / STEP) * Math.cos((lat * Math.PI) / 180)));
  const dl = 360 / n;
  for (let i = 0; i < n; i++) {
    const lon = -180 + (i + (row % 2) * 0.5) * dl;
    if (fc.features.some((f) => booleanPointInPolygon([lon, lat], f))) out.push(Math.round(lat * 10), Math.round(lon * 10));
  }
}
const buf = Buffer.alloc(out.length * 2);
out.forEach((v, i) => buf.writeInt16LE(v, i * 2));
fs.writeFileSync(
  "src/lib/globe-dots.ts",
  `// Generated by scripts/globe-dots.mjs from Natural Earth 110m land (public domain): ${out.length / 2} points on land,\n// rows ${STEP} degrees apart, as little-endian int16 pairs of (lat, lon) times ten, base64. Do not edit by hand.\nexport const GLOBE_DOTS_B64 =\n  "${buf.toString("base64")}";\n`,
);
console.log(`${out.length / 2} dots written to src/lib/globe-dots.ts`);
